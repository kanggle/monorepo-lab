import { NextResponse } from 'next/server';
import { resolveDemoBackendState } from '@/shared/config/demo-backend';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

/**
 * 데모 백엔드의 **방문 시점** 판정 (`TASK-MONO-654`).
 *
 * =============================================================================
 * 🔴🔴 왜 라우트 핸들러인가 — 배너가 서버 컴포넌트였을 때 판정이 **구워졌다**
 * =============================================================================
 * `DemoBackendNotice` 는 레이아웃 안의 async 서버 컴포넌트였고, 그 레이아웃은
 * `export const revalidate = 60` 인 라우트를 감싼다. ⇒ 판정이 **프리렌더 시점**에
 * 실행돼 정적 사본에 그대로 구워졌다.
 *
 * 🔴 그리고 그 사본은 **재생성되지 않았다.** 실측(2026-09-11, 표본 5개 / 이틀):
 * `Age` 가 벽시계와 **정확히** 같이 흐르고 `X-Vercel-Cache: STALE` 이 안 풀린다.
 * 다섯 표본이 전부 사본 생성 시각 `2026-09-09T21:59Z` 로 수렴했다 — 40시간 동안
 * **재생성 0회**. `revalidate = 60` 이 선언돼 있는데도 그렇다.
 *
 * ⇒ 🔴 「트래픽이 없어서」 갈래는 **반증됐다**(요청은 계속 있었고 나이는 한 번도 안
 *   줄었다). 그러므로 **캐시 수명을 줄이는 처방은 이 상태를 안 고친다.**
 *   판정을 캐시된 사본 **밖으로** 빼는 것만이 유효하다. 그것이 이 파일이다.
 *
 * -----------------------------------------------------------------------------
 * 🔴 `force-dynamic` 과 `no-store` 는 **둘 다** 필요하다
 * -----------------------------------------------------------------------------
 * 앞의 것은 Next 가 이 라우트를 프리렌더하지 않게 하고, 뒤의 것은 그 앞의 CDN 이
 * 응답을 붙들지 않게 한다. 하나만 있으면 이 티켓의 결함이 **한 층 위에서 재발한다** —
 * 정적 사본 대신 엣지 사본에 같은 판정이 굳는다.
 *
 * -----------------------------------------------------------------------------
 * 🔴 `DEMO_API_BASE` 를 **여기서 읽지 않는다** (TASK-MONO-635 과 같은 이유)
 * -----------------------------------------------------------------------------
 * 그 이름은 `@demo/backend-resolver` 가 소유하는 계약이다(`ADR-MONO-068 § D6 = B2`).
 * 이 라우트는 앱의 소비자 모듈을 통해 **판정만 위임**받는다 —
 * `scripts/check-demo-resolver-copies.sh` 가 그 중복을 문다.
 *
 * 🔵 익명 방문자가 부를 수 있어야 한다 — 이 배너는 **로그인하지 않은 방문자**에게
 *    보여 주려고 있는 것이다. `middleware.ts` 의 공개 목록에 이 경로가 있고, 없으면
 *    익명 요청이 `/login` 으로 307 되어 배너가 **영영 안 뜬다**(그 대상이 정확히
 *    이 기능의 청중이다).
 */
export async function GET(): Promise<Response> {
  const state = await resolveDemoBackendState();
  return NextResponse.json(
    { state },
    // 🔴 판정은 «지금» 의 사실이다. 한 겹이라도 캐시되면 이 티켓이 그대로 재발한다.
    { headers: { 'Cache-Control': 'no-store, no-cache, must-revalidate' } },
  );
}
