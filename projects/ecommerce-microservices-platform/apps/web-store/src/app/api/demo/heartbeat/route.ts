import { getWebStoreSession } from '@/shared/auth/session';
import { sendDemoHeartbeat } from '@demo/backend-resolver';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

/**
 * 데모 EC2 의 idle-stop 타이머를 미루는 하트비트 중계 (`POST ${DEMO_API_BASE}/heartbeat`).
 *
 * =============================================================================
 * 🔴🔴 왜 «세션이 있을 때만» 인가 — 공개 열람이 EC2 를 켜 두면 안 된다
 * =============================================================================
 * 공개 카탈로그는 이제 백엔드 없이 저장본만으로 돈다. 그 화면을 보는 방문자는 EC2 를
 * **쓰지 않는다.** 그런데 하트비트를 무조건 보내면, 검색엔진 크롤러 한 마리나 탭 하나를
 * 열어 둔 방문자가 아무도 쓰지 않는 인스턴스를 **몇 시간이고 켜 둔다** — 그리고 그 비용은
 * 월 예산 가드(`infra/demo/aws/terraform/lambda/handler.py` § MONTHLY_BUDGET_MINUTES)를
 * 태워서, 정작 백엔드가 필요한 사람이 `/start` 를 429 로 거절당한다.
 * ⇒ 하트비트는 «이 사람이 백엔드를 실제로 쓰고 있다» 의 신호여야 하고, 이 앱에서 그것과
 *   가장 가까운 관측 가능한 사실이 **로그인 세션**이다.
 *
 * 익명·미설정(`DEMO_API_BASE` 없음 = 로컬·CI·비데모 배포)일 때는 **아무 데도 안 보내고**
 * 204 를 돌려준다. 🔵 401 이 아니라 204 인 이유: 이것은 인가가 필요한 자원이 아니라
 * fire-and-forget 비콘이고, 익명 방문은 «오류» 가 아니라 **정상적인 무동작**이다.
 *
 * 🔵 게이트가 둘이다. `middleware.ts` 가 이 경로를 이미 막는다(공개 목록에 없다) — 그래서
 *    미들웨어를 **손대지 않았다**. 하지만 그것에 기대지 않는다: 미들웨어의 공개 목록은
 *    앞으로 누군가 넓힐 수 있고, 그때 이 라우트가 조용히 열리면 안 된다. 여기 세션 검사가
 *    실제로 무는 게이트이고, 유닛 테스트가 무는 것도 이쪽이다.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * 🔴🔴 `DEMO_API_BASE` 를 **여기서 읽지 않는다** (TASK-MONO-635)
 * ─────────────────────────────────────────────────────────────────────────
 * 그 이름은 `@demo/backend-resolver` 가 소유하는 **계약**이고(`ADR-MONO-068 § D6 = B2`),
 * 세 앱이 각자 읽으면 계약이 네 집을 갖는다 — 형태가 바뀌는 날 한 곳만 고쳐진다.
 * `scripts/check-demo-resolver-copies.sh` 가 그 중복을 정적으로 물었고, **가드가 옳았다.**
 *
 * 🔴 지문을 문법으로 피하지 않았다(상수로 감싸 `process.env[NAME]` 로 쓰면 가드는 통과하되
 *    중복은 그대로다 — 그건 고침이 아니라 회피다). 대신 패키지가 `sendDemoHeartbeat()` 를
 *    내보내고 이 라우트는 **세션 판정 + 위임**만 한다.
 * 🔵 세션 판정이 여기 남는 것은 의도다 — 앱마다 세션 기전이 다르므로 패키지가 그것을
 *    알면 안 된다. 「익명은 안 보낸다」(ADR-MONO-071 § D8)의 책임은 호출부에 있다.
 */
export async function POST(): Promise<Response> {
  const session = await getWebStoreSession();
  // 🔴 세션을 **먼저** 본다. «세션이 없다» 와 «데모가 아니다» 둘 다 무동작이지만, 세션
  //    검사를 건너뛰는 분기가 생기면 그 순간 익명 하트비트가 가능해진다.
  if (!session.accountId) {
    return new Response(null, { status: 204 });
  }

  // 🔵 컨트롤 플레인이 잠깐 죽은 것을 사용자 화면의 오류로 번역하지 않는다. 다음 틱이
  //    다시 시도한다(놓친 비트 하나는 idle 타이머를 넘기지 않는다 — 틱 60초 vs 타이머 분 단위).
  //    `DEMO_API_BASE` 가 없는 배포에서는 'not-demo' 를 돌려주고 아무 데도 안 보낸다.
  await sendDemoHeartbeat();
  return new Response(null, { status: 204 });
}
