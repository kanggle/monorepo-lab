import { NextResponse } from 'next/server';
import { isAuthenticated } from '@/shared/auth/session';
import { sendDemoHeartbeat } from '@demo/backend-resolver';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

/**
 * 데모 EC2 의 유휴 종료 타이머를 미루는 heartbeat 중계.
 *
 * ═════════════════════════════════════════════════════════════════════════
 * 🔴🔴 **공개 브라우징은 인스턴스를 살려 두면 안 된다** — 이 라우트의 존재 이유다
 * ═════════════════════════════════════════════════════════════════════════
 * 데모 백엔드는 `infra/demo/aws` 의 Lambda 가 관리하고, 그 Lambda 는 *"heartbeat 이
 * 끊긴 지 N 분"* 이면 인스턴스를 stop 한다(`variables.tf` 의 유휴 종료 임계값). 즉
 * heartbeat 는 단순한 텔레메트리가 아니라 **비용을 쓰는 행위**다 — 한 번 보낼 때마다
 * 종료 시각이 뒤로 밀린다.
 *
 * 공개 브라우징이 생기면서 새 위험이 하나 생겼다: 이제 이 사이트는 **로그인 없이도**
 * 뜨고, 검색 크롤러·링크 미리보기·우연한 방문자가 아무 때나 페이지를 연다. 그 방문에
 * heartbeat 이 딸려 나가면 아무도 안 쓰는 백엔드가 **무기한 켜져 있게 되고**, 그 비용은
 * 조용히 나간다(아무도 안 보고 있으니 증상도 없다).
 *
 * 그리고 그 결합은 **거짓이기도 하다**: 공개 화면은 저장본만 읽으므로 백엔드가 켜져
 * 있든 꺼져 있든 똑같이 동작한다. 익명 방문자가 보내는 heartbeat 은 «누군가 백엔드를
 * 쓰고 있다» 는 신호로 읽히지만 실제로는 아무도 안 쓴다 — 없는 사실을 주장하는 신호다.
 *
 * ⇒ 세션이 없으면 **아무 일도 안 한다.** 그 판정을 클라이언트에 맡기지 않는 이유도 같다:
 *   클라이언트 조건은 «안 부른다» 일 뿐이고, 누구든 이 URL 을 직접 칠 수 있다. 판정은
 *   서버에서, 세션 헬퍼로 한다.
 *
 * 🔵 204 로 답하는 이유: 401 을 주면 클라이언트 콘솔에 빨간 줄이 쌓이고, 그것은 «고장» 처럼
 *    보이는데 실제로는 **설계대로 동작한 것**이다. 익명 방문자의 heartbeat 은 오류가 아니라
 *    무의미한 요청이므로, 조용히 아무 일도 안 했다고 답한다. `DEMO_API_BASE` 가 없는
 *    로컬·CI 도 같은 이유로 204 다 — 거기엔 살려 둘 인스턴스 자체가 없다.
 *
 * 🔵 이 경로는 `shared/auth/public-paths.ts` 의 허용 목록에 **없다.** 즉 익명 POST 는
 *    미들웨어에서 이미 `/login` 으로 꺾인다. 아래 세션 검사는 그와 **별개의 겹**이다 —
 *    가드가 한 겹이면 그 한 겹이 빠진 날(허용 목록에 `/api` 가 실수로 들어가는 날) 조용히
 *    통과한다. 두 겹의 판정 근거가 서로 독립이어야 의미가 있으므로 여기서 다시 묻는다.
 * ═════════════════════════════════════════════════════════════════════════ *
 * ─────────────────────────────────────────────────────────────────────────
 * 🔴🔴 `DEMO_API_BASE` 를 **여기서 읽지 않는다** (TASK-MONO-635)
 * ─────────────────────────────────────────────────────────────────────────
 * 그 이름은 `@demo/backend-resolver` 가 소유하는 **계약**이고(`ADR-MONO-068 § D6 = B2`),
 * 세 앱이 각자 읽으면 계약이 네 집을 갖는다 — 형태가 바뀌는 날 한 곳만 고쳐진다.
 * `scripts/check-demo-resolver-copies.sh` 가 그 중복을 정적으로 물었고, **가드가 옳았다.**
 *
 * 🔴 지문을 문법으로 피하지 않았다(상수로 감싸 `process.env[NAME]` 로 쓰면 가드는 통과하되
 *    중복은 그대로다 — 그건 고침이 아니라 회피다). 대신 패키지가 `sendDemoHeartbeat()` 를
 *    내보내고 이 라우트는 **세션 판정 + 위임**만 한다.
 * 🔵 세션 판정이 여기 남는 것은 의도다 — 앱마다 세션 기전이 다르므로 패키지가 그것을
 *    알면 안 된다. 「익명은 안 보낸다」(ADR-MONO-071 § D8)의 책임은 호출부에 있다.
 */
export async function POST() {
  // 🔴 순서가 중요하다. 세션을 **먼저** 본다 — 그래야 「`DEMO_API_BASE` 가 설정된 실제
  //    데모 배포에서 익명 요청이 왔다」는 위험한 칸이 여기서 걸린다. 반대로 두면 그 칸이
  //    두 번째 조건에 가려 시험할 수 없다(`demo-heartbeat-route.test.ts` 가 그 칸이다).
  if (!(await isAuthenticated())) {
    return new NextResponse(null, { status: 204 });
  }

  // 🔵 컨트롤 플레인이 답을 못 줘도 화면은 아무 영향을 안 받는다. heartbeat 은 «해 두면
  //    좋은 일» 이지 화면의 전제가 아니므로, 실패를 방문자에게 전가하지 않는다.
  //    (`sendDemoHeartbeat()` 이 타임아웃·네트워크 실패를 삼키고 결과만 돌려준다.)
  await sendDemoHeartbeat();
  return new NextResponse(null, { status: 204 });
}
