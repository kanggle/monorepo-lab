/**
 * `CONSOLE_PUBLIC_ORIGIN` → `NEXT_PUBLIC_APP_URL` → `http://console.local`.
 *
 * 🔴 순서를 바꾸지 마라. `TASK-MONO-358` 이 정한 순서이고, 그 이유는 `env.ts` 의
 * `CONSOLE_PUBLIC_ORIGIN` JSDoc 에 있다: `NEXT_PUBLIC_*` 은 **빌드 타임에 인라인**되므로
 * 미리 구운 이미지는 빌드가 알던 호스트에 영구히 묶인다. 접두사 없는 이름은 인라인되지
 * 않고 **런타임에 읽힌다.**
 *
 * 🔵 마지막 폴백은 로컬 개발용이다(`console.local` = Traefik 별칭). 이 리터럴이 여기
 * 있어도 되는 이유는 이 모듈이 클라이언트 그래프에 **닿지 않기** 때문이고, 그 성질은
 * `scripts/check-console-backend-urls.sh` 칸 (4)가 지킨다.
 */
export function selfOrigin(): string {
  const raw =
    process.env.CONSOLE_PUBLIC_ORIGIN ??
    process.env.NEXT_PUBLIC_APP_URL ??
    'http://console.local';
  return raw.replace(/\/$/, '');
}
