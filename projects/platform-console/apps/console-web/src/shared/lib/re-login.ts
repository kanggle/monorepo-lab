/**
 * 강제 재로그인 마커 (`TASK-PC-FE-278`).
 *
 * -----------------------------------------------------------------------------
 * 🔴🔴 왜 이 상수가 생겼나 — **재로그인이 재로그인이 아니었다**
 * -----------------------------------------------------------------------------
 * `console-integration-contract` 는 스무 곳 넘게 같은 말을 적어 뒀다:
 * *"`401` → forced **whole-session** re-login (no partial authed state)"*,
 * 그리고 § 2.4.6/§ 2.4.7 은 아예 **"never a re-login loop"** 라고 못박았다.
 *
 * 그런데 코드가 하던 일은 `redirect('/login')` 하나였고, `/login` 페이지의 첫 줄은
 *
 * ```ts
 * if (await isAuthenticated()) redirect('/console');
 * ```
 *
 * 이며 {@link isAuthenticated} 는 **쿠키만** 읽는다(백엔드에 묻지 않는다). 백엔드가
 * 토큰을 거절해도 쿠키는 멀쩡하므로 —
 *
 * ```
 *   /ecommerce ──401──▶ /login ──쿠키 있음──▶ /console
 * ```
 *
 * 재로그인하러 보낸 사람이 **아무 말도 없이 카탈로그로 되돌아온다.** 방문자가 보는 것은
 * 「반짝임」 하나이고, 세션은 죽은 채로 남는다. 계약이 금지한 그 루프다.
 *
 * 🔵 **판정의 술어가 문제였던 게 아니다** — 쿠키만 보는 것은 `/login` 입장에서 합리적이다.
 * 문제는 **401 이 일어났다는 사실이 `/login` 에 전달되지 않는 것**이었다. 그래서 고침은
 * 술어 교체가 아니라 **정보 채널의 신설**이다: 401 지점이 이 마커를 붙이고, `/login` 은
 * 마커가 있으면 단락 회로를 타지 않는다.
 *
 * -----------------------------------------------------------------------------
 * 🔴 이 값은 **문자열 리터럴로 53곳에 박혀 있다** — 그리고 그것이 의도다
 * -----------------------------------------------------------------------------
 * 401 지점들은 `redirect('/login?error=session_expired')` 를 **리터럴로** 쓴다.
 * 이 상수를 import 하지 않는다. 이유:
 *
 * - 그 53곳은 이미 `'/login'` 을 리터럴로 쓰고 있었다. 상수를 도입하면 51개 파일에
 *   import 를 더해야 하고, 그 51줄이 이 수리의 진짜 내용을 덮는다.
 * - 🔴 그리고 **상수는 규율을 강제하지 못한다** — 새 코드가 그냥 `redirect('/login')` 을
 *   써도 상수는 아무 말도 안 한다. 강제는 테스트가 한다:
 *   `src/__tests__/relogin-marker.test.ts` 가 소스에서 **마커 없는 `redirect('/login')`**
 *   을 찾아 빨개진다. 그 테스트가 이 파일보다 중요하다.
 *
 * ⇒ 이 상수의 몫은 **읽는 쪽**(`/login` 페이지·테스트)이 오타 없이 같은 값을 쓰는 것이고,
 *   쓰는 쪽 53곳의 일관성은 테스트가 지킨다.
 */
export const SESSION_EXPIRED = 'session_expired';

/**
 * 401 지점이 꺾어야 하는 목적지. 🔴 **리터럴과 반드시 같아야 한다** —
 * `relogin-marker.test.ts` 가 이 값으로 소스를 검사한다.
 */
export const RE_LOGIN_PATH = `/login?error=${SESSION_EXPIRED}`;
