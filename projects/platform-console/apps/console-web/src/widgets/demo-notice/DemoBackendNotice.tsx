//    가드의 눈을 피하는 습관이 생긴다.
import { resolveDemoBackendState } from '@/shared/config/demo-backend';

/**
 * 데모 백엔드가 꺼져 있을 때 **그렇다고 말한다** (`TASK-MONO-585` AC-3 /
 * `ADR-MONO-067` 단계 3).
 *
 * 🔴 왜 필요한가 — 콘솔이 Vercel 로 옮겨 가면서 **새로 생긴 상태**다. 예전에는 화면이 데모
 * 호스트의 컨테이너였으므로 백엔드가 꺼지면 화면도 같이 사라졌다. 이제 화면은 Vercel 에서
 * **멀쩡히 뜨고** 데이터만 없다 ⇒ 아무 말도 안 하면 방문자는 **빈 대시보드를 "고장"** 으로
 * 읽는다.
 *
 * 🔵 서버 컴포넌트다 — 판정이 `DEMO_API_BASE`(비공개 env)에 달려 있고, 그 이름이 클라이언트
 * 번들에 들어가면 안 된다.
 *
 * 🔴 로컬 개발과 CI 에서는 **아무것도 렌더하지 않는다**(`not-demo`). 거기서 "데모가 꺼졌다"
 * 고 말하는 것은 거짓이다 — 애초에 데모가 아니다. 판정을 가르는 것은 백엔드의 상태가 아니라
 * **컨트롤 플레인이 설정돼 있는가**(= 이 배포가 데모인가)이다.
 *
 * -----------------------------------------------------------------------------
 * 🔴🔴 문구가 «여덟 곳이 다 죽었다» 라고 말하지 않는 이유 — **그건 안 잰 것이다**
 * -----------------------------------------------------------------------------
 * 이 티켓의 AC-3 이 미리 경고했다: *"콘솔은 여덟 곳 중 일부만 죽을 수 있다 — «전부 아니면
 * 전무» 로 표현하면 거짓말이 된다."* 그래서 이 위젯이 말하는 것은 **도메인의 상태가 아니라
 * 인스턴스의 상태**다. 해석기가 재는 것은 컨트롤 플레인의 `state` 한 칸이고, 그것이
 * `running` 이 아니면 여섯 도메인이 **한 EC2 인스턴스와 함께** 꺼져 있다 — 그때는 「전부」가
 * 참이다. 반대로 인스턴스가 켜져 있는데 한 도메인만 죽은 경우는 이 위젯이 **아무 말도 하지
 * 않는다**: 그 축을 재는 화면이 이미 따로 있다(`/dashboards/health` — 도메인별 카드).
 * ⇒ 두 축을 한 문장으로 합치지 않는다. 합치는 순간 둘 중 하나는 거짓이 된다.
 *
 * -----------------------------------------------------------------------------
 * 🔴 `/login` 을 **덮는다** — 형제(fan)와 갈리는 지점이고, 근거가 있다
 * -----------------------------------------------------------------------------
 * fan 의 같은 위젯은 `/login` 을 일부러 비워 뒀다(*"로그인 실패는 다른 증상이라 다른 처방이
 * 필요하다"*). 콘솔은 반대다: `page.tsx` **67개 중 익명으로 닿는 것이 `/login` 하나**이고
 * (나머지 66개는 `(console)/layout.tsx` 의 `isAuthenticated()` 가드 뒤), 데모가 꺼지면
 * IdP 도 같이 꺼져 로그인 자체가 실패한다. 즉 콘솔에서 이 위젯을 로그인에 안 달면,
 * **데모가 꺼진 동안 방문자가 보는 유일한 화면에 아무 설명이 없다.**
 * 🔵 fan 의 판단이 틀렸다는 뜻이 아니다 — fan 은 익명 표면이 피드였고 콘솔은 아니다.
 */
export async function DemoBackendNotice() {
  const state = await resolveDemoBackendState();
  if (state !== 'unavailable') return null;

  return (
    <div
      role="status"
      data-testid="demo-backend-notice"
      style={{
        background: '#fef3c7',
        color: '#92400e',
        padding: '10px 16px',
        fontSize: '0.9rem',
        textAlign: 'center',
        borderBottom: '1px solid #fcd34d',
      }}
    >
      데모 서버가 꺼져 있어 로그인과 운영 데이터를 사용할 수 없습니다. 데모 시작
      페이지에서 서버를 켠 뒤(약 10분) 다시 열어 주세요.
    </div>
  );
}
