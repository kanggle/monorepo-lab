import { NextResponse } from 'next/server';
import { isAuthenticated } from '@/shared/lib/session';
import { sendDemoHeartbeat } from '@demo/backend-resolver';

export const runtime = 'nodejs';

/**
 * =============================================================================
 * 데모 인스턴스 keep-alive — **로그인한 운영자가 쓰는 동안만** 켜 둔다
 * =============================================================================
 * 데모 백엔드는 예산이 정해진 EC2 인스턴스 하나이고, 컨트롤 플레인(API Gateway +
 * Lambda)이 «마지막 하트비트» 를 보고 유휴 인스턴스를 stop 한다
 * (`infra/demo/aws/terraform/lambda/handler.py` § heartbeat / 최대 가동시간 / 월 예산).
 * 그러니 "누가 이 인스턴스를 살려 두는가" 는 **예산을 누가 쓰는가** 와 같은 질문이다.
 *
 * 🔴🔴 **공개 둘러보기(`/demo`)는 하트비트를 보내지 않는다.** 익명 방문자가 탭을 열어 둔
 *    것만으로 EC2 가 계속 돌면, 정작 로그인해서 기능을 쓰려는 사람이 도착했을 때 예산이
 *    이미 소진돼 있다. 그리고 둘러보기는 **백엔드가 꺼져 있어도 완전히 동작한다**(값이
 *    저장본에서 온다) — 즉 그 화면은 인스턴스를 켜 둘 이유 자체가 없다.
 *    ⇒ 그 성질을 문서가 아니라 **두 곳의 구조**로 만든다:
 *        ① 핑거(`widgets/demo-heartbeat`)를 `(console)` 셸에만 마운트한다.
 *        ② 그리고 이 라우트가 **다시** 세션을 확인한다. ①만으로는 부족하다 —
 *          `POST /api/demo/heartbeat` 는 누구나 curl 로 부를 수 있고, 그때 ①은
 *          아무것도 막지 못한다. 서버에서 다시 확인하는 것이 진짜 경계다.
 *
 * 🔵 익명·미설정 응답이 **에러가 아니라 204** 인 이유: 이 엔드포인트는 «권한 검사» 가
 *    아니라 «신호 중계» 다. 401 을 주면 둘러보기 화면의 콘솔에 빨간 줄이 남고 방문자는
 *    그것을 고장으로 읽는다. 아무 일도 안 한 것을 «아무 일도 안 했다»(204) 로 말한다.
 *
 * -----------------------------------------------------------------------------
 * 🔵 `DEMO_API_BASE` 를 여기서 **안 읽는다** — 그 부채는 갚았다 (TASK-MONO-635)
 * -----------------------------------------------------------------------------
 * 이 자리에는 «지문을 피하려고 env 이름을 상수로 감쌌다» 는 정직한 기록이 있었고, 그
 * 기록이 스스로 *"옳은 모양은 이것이 아니다"* 라고 적으며 정본을 지목했다:
 * `@demo/backend-resolver` 가 컨트롤 플레인 베이스를 읽는 유일한 자리여야 한다.
 *
 * 🔴 그리고 `scripts/check-demo-resolver-copies.sh` 가 **세 앱을 전부 물었다** — 회피는
 *    통하지 않았고, 통했더라도 중복은 그대로 남았을 것이다. 가드가 옳았다.
 * ⇒ 그 패키지가 `sendDemoHeartbeat()` 를 내보내고, 이 라우트는 **세션 판정 + 위임**만 한다.
 * 🔵 세션 판정이 여기 남는 것은 의도다 — 앱마다 세션 기전이 다르므로(next-auth 둘, 자체
 *    쿠키 하나) 패키지가 그것을 알면 안 된다. 「익명은 안 보낸다」의 책임은 호출부에 있다.
 * =============================================================================
 */

/** 아무 일도 안 했음. 본문 없음 — 호출부(핑거)는 응답을 읽지 않는다. */
function noop(): NextResponse {
  return new NextResponse(null, { status: 204 });
}

export async function POST(): Promise<NextResponse> {
  // 🔴 순서가 중요하다. 세션 확인이 **먼저**다 — env 를 먼저 보면 로컬·CI 에서
  //    "설정이 없어서 통과했다" 와 "익명이라 통과했다" 가 같은 모양이 되고, 테스트가
  //    익명 no-op 을 증명하지 못한다.
  if (!(await isAuthenticated())) return noop();

  // 🔵 로컬 개발·CI·컨테이너 데모에는 컨트롤 플레인이 없다 — 그때 `sendDemoHeartbeat()` 는
  //    'not-demo' 를 돌려주고 아무 데도 안 보낸다. 결함이 아니라 선언된 상태다.
  // 🔵 실패도 삼킨다. 컨트롤 플레인이 잠깐 죽었다고 운영자 화면에 오류를 띄우지 않는다 —
  //    하트비트가 몇 번 빠지면 인스턴스가 멈출 뿐이고, 그 상태는 `DemoBackendNotice` 가
  //    이미 말한다. 여기서 상태 코드를 바꾸면 «백엔드 장애» 가 «콘솔 장애» 로 보인다.
  await sendDemoHeartbeat();

  return noop();
}
