/**
 * 둘러보기가 보여 주는 **쓰기 작업 버튼들** — 전부 비활성이다.
 *
 * =============================================================================
 * 🔴🔴 왜 버튼을 «지우지 않고» 비활성으로 그리는가
 * =============================================================================
 * 요구사항이 명시했다: *"각 화면이 무슨 일을 하는지 보여 준다."* 승인·저장·삭제 버튼을
 * 통째로 빼면 그 화면은 **읽기 전용 리포트처럼** 보이고, 방문자는 이 콘솔이 실제로
 * 무엇을 운영하는지 알 수 없다. 반대로 눌리는 버튼을 두면 «아무 일도 안 일어나는
 * 버튼» 이 되고, 그것은 고장과 구별되지 않는다.
 * ⇒ **보이되 눌리지 않고, 왜 안 눌리는지 그 자리에서 말한다.**
 *
 * 🔴 그 성질을 «호출부가 `disabled` 를 잊지 않는 것» 으로 얻지 않는다. 잊을 수 있고,
 *    잊은 것은 조용하다. {@link DemoActionButton} 은 `disabled` 를 **받지 않는다** —
 *    항상 비활성으로 렌더한다. 활성 버튼을 그리려면 그 컴포넌트를 안 쓰는 수밖에 없고,
 *    그것은 리뷰에서 보인다(그리고 테스트가 «둘러보기의 모든 버튼이 비활성인가» 를 잰다).
 *
 * 🔵 라벨의 출처: 각 표의 `key` 는 **실제 콘솔 화면의 것과 같다**(샘플 픽스처 헤더가
 *    그렇게 적어 두었다). 그래서 여기 적는 작업 이름도 그 실제 화면이 실제로 하는 일이다 —
 *    없는 기능을 그려 넣지 않는다.
 */

/** 비활성 사유. 요구사항이 지정한 **정확한 문구**이며, 툴팁과 안내문이 이 하나를 공유한다. */
export const DEMO_DISABLED_REASON = '실시간 기능 시작 후 로그인';

/**
 * 표 `key` → 그 화면의 쓰기 작업 이름들.
 *
 * 🔴 여기 없는 표는 **버튼을 안 그린다**(빈 배열). 「기본값으로 생성/수정/삭제를 붙인다」
 *    같은 폴백을 두면, 새 표가 추가되는 날 **그 화면에 없는 기능**이 자동으로 그려진다.
 *    없는 사실을 주장하는 화면이 되는 경로이고, 침묵이 더 정직하다.
 */
const ACTIONS_BY_TABLE: Readonly<Record<string, readonly string[]>> = {
  // overview — 도메인 헬스는 읽기 전용 집계다. 쓰기 작업이 없다(그래서 빈 칸이 아니라
  // 아예 항목이 없다 — 위 주석의 «침묵» 규칙 그대로).
  orders: ['주문 상태 변경', '환불 승인'],
  products: ['상품 등록', '가격 수정', '판매 중지'],
  inventory: ['재고 조정', '로케이션 이동'],
  procurement: ['발주 승인', '발주 생성'],
  approval: ['승인', '반려', '위임'],
  ledger: ['전표 생성', '기간 마감'],
  tenants: ['테넌트 생성', '운영자 초대', '구독 변경'],
};

/** 이 표가 실시간 콘솔에서 제공하는 쓰기 작업 이름들(없으면 빈 배열). */
export function actionsForTable(tableKey: string): readonly string[] {
  return ACTIONS_BY_TABLE[tableKey] ?? [];
}
