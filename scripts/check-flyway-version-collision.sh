#!/usr/bin/env bash
# =============================================================================
# check-flyway-version-collision.sh — 한 서비스 안에 같은 Flyway 버전 번호가 둘
# =============================================================================
# TASK-MONO-669. 🔴 **실제로 밟아서 만든 가드다** (`TASK-MONO-659`, 2026-09-11).
#
# 무엇이 일어났나
# -----------------------------------------------------------------------------
# `outbound-service` 에 `V10__order_schema_align.sql` 이 이미 있는데 같은 번호로
# `V10__denormalise_sku_code_on_order_line.sql` 을 넣었다. Flyway 는 기동할 때
# 죽는다:
#
#     Caused by: org.flywaydb.core.api.FlywayException
#         at CompositeMigrationResolver.java:92
#
# 🔴🔴 **그 신호가 「번호가 겹쳤다」로 안 보인다.** 보이는 것은 Testcontainers 통합
#    테스트 **15개가 무더기로 FAILED** 인 화면이고, 그중 어느 것도 마이그레이션을
#    말하지 않는다(전부 «컨텍스트 기동 실패» 의 파생이다). 진단에 왕복 한 번이 든다.
#
# 🔴 그리고 **로컬에서는 안 보인다** — 이 저장소의 Testcontainers IT 는 로컬에서
#    못 돌린다(알려진 블로커). ⇒ CI 에 밀어 넣기 전에는 알 방법이 없었다. 이 가드가
#    그 간극을 메운다.
#
# -----------------------------------------------------------------------------
# 🔴 왜 「최대 버전」을 눈으로 보면 안 되나 — 술어가 **알파벳 정렬**이었다
# -----------------------------------------------------------------------------
# 659 는 `ls <dir> | tail -8` 로 마지막 버전을 봤다. `ls` 는 **알파벳 순**이라
# `V10` 이 `V2` 보다 **앞**에 오고, `tail` 이 그 구간을 통째로 잘라냈다.
# 보인 최대값 `V9`, 실제 최대값 **`V18`**.
# ⇒ 「V10 은 없다」가 아니라 **「내가 쓴 목록에 V10 이 안 보였다」** 였다.
#
# 🔵 올바른 술어는 **숫자 정렬**이다. 이 스크립트가 그것을 한다:
#     find … -name 'V*.sql' | sed 's|.*/V||;s|__.*||' | sort -n
#
# -----------------------------------------------------------------------------
# 모집단 — `git ls-files` (인덱스)
# -----------------------------------------------------------------------------
# 🔴 그래서 **스테이지 전에 돌리면 새 파일이 안 보인다.** 이 저장소의 다른 가드들과
#    같은 규약이고 같은 함정이다: `git add` → 모집단 확인 → 가드 실행.
#    🔵 CI 는 커밋된 트리를 읽으므로 영향이 없다.
#
# -----------------------------------------------------------------------------
# 🔴 이 가드가 재지 **못하는** 것
# -----------------------------------------------------------------------------
#  1. **서비스 «사이» 의 같은 번호** — 그건 정상이다. 각 서비스가 자기 스키마 이력을
#     따로 갖는다(`admin-service V4` 와 `outbound-service V4` 는 무관하다).
#  2. **이미 적용된 마이그레이션의 내용 변경**(체크섬 위반) — 다른 축이고, 그건
#     Flyway 가 런타임에 문다. 여기서는 파일 이름만 본다.
#  3. **번호는 안 겹치는데 순서가 틀린 것** — 의미는 안 본다.
# =============================================================================
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 1

say() { printf '%s\n' "$*"; }
die() { printf '\n❌ check-flyway-version-collision: %s\n' "$*" >&2; exit 1; }

# --- 모집단 ------------------------------------------------------------------
mapfile -t FILES < <(git ls-files '*/db/migration/V*.sql' | sort)
n_files="${#FILES[@]}"

# 🔴🔴 비공허성 — 파일이 0개면 아래 검사는 **언제나 참**이고, 그것은 통과가 아니다.
#    (술어가 바뀌었거나 경로 관례가 바뀐 것이고, 둘 다 조용히 지나갈 일이 아니다.)
if [ "$n_files" -eq 0 ]; then
  die "마이그레이션 파일이 **0개**입니다.

이 상태에서는 「중복 없음」이 «아무것도 안 봤음» 과 구별되지 않습니다.
  · 경로 관례가 바뀌었나요? 이 가드는 \`*/db/migration/V*.sql\` 을 봅니다.
  · 🔴 **스테이지 전에 돌렸나요?** 모집단은 \`git ls-files\`(인덱스)입니다 —
    \`git add\` 하지 않은 새 파일은 여기에 **없습니다**."
fi

# --- 디렉터리별로 버전 번호를 모은다 -----------------------------------------
declare -A SEEN=()      # "<dir>|<version>" -> 첫 파일명
dupes=0
report=""

for f in "${FILES[@]}"; do
  dir="${f%/*}"
  base="${f##*/}"
  # V<번호>__<설명>.sql — 번호는 `.` 을 포함할 수 있다(V1.1 같은 판).
  ver="${base#V}"
  ver="${ver%%__*}"
  [ -n "$ver" ] || continue
  key="${dir}|${ver}"
  if [ -n "${SEEN[$key]:-}" ]; then
    dupes=$((dupes + 1))
    report+="  · ${dir}
      V${ver}  ←  ${SEEN[$key]}
      V${ver}  ←  ${base}
"
  else
    SEEN[$key]="$base"
  fi
done

n_dirs="$(printf '%s\n' "${FILES[@]}" | sed 's|/[^/]*$||' | sort -u | wc -l | tr -d ' ')"

if [ "$dupes" -gt 0 ]; then
  say ""
  say "❌ check-flyway-version-collision: 같은 서비스 안에 **버전 번호가 겹칩니다** (${dupes}건)."
  say ""
  printf '%s' "$report"
  say "🔴 Flyway 는 기동할 때 죽습니다 — \`FlywayException at CompositeMigrationResolver\`."
  say "   그리고 그 신호는 «번호가 겹쳤다» 로 안 보입니다: **통합 테스트가 무더기로 FAILED** 로"
  say "   보이고 그중 어느 것도 마이그레이션을 말하지 않습니다."
  say ""
  say "고치는 법 — 🔴 최대 버전을 \`ls | tail\` 로 보지 마십시오(알파벳 정렬이라 V10 이 V2 앞입니다):"
  say "   find <dir> -name 'V*.sql' | sed 's|.*/V||;s|__.*||' | sort -n | tail -1"
  exit 1
fi

say "check-flyway-version-collision: OK — 마이그레이션 ${n_files}개 / 디렉터리 ${n_dirs}개, 같은 서비스 안 번호 중복 0건."
say "  (모집단 = \`git ls-files\`. 🔴 스테이지 전에 돌리면 새 파일이 안 보입니다.)"
say "  🔴 재지 않는 것: 서비스 «사이» 의 같은 번호(정상) · 체크섬 위반 · 번호는 다른데 순서가 틀린 것."
exit 0
