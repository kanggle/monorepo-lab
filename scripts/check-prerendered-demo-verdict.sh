#!/usr/bin/env bash
# =============================================================================
# check-prerendered-demo-verdict.sh — 프리렌더된 사본에 «데모 백엔드 판정» 이 구워졌나
# =============================================================================
# TASK-MONO-654.
#
# 무엇을 막나
# -----------------------------------------------------------------------------
# `DemoBackendNotice` 는 `app/(store)/layout.tsx` 에 있고, 그 레이아웃은 프리렌더되는
# 라우트들을 감싼다. 그 컴포넌트가 백엔드 상태를 **서버에서 판정**하면 그 판정이 정적
# 사본에 **구워진다** — 그리고 이 배포에서 그 사본은 재생성되지 않는다.
#
# 🔴 실측(2026-09-11, 표본 5개 / 이틀): `store /` 의 `Age` 가 벽시계와 **정확히** 같이
#    흐르고 `X-Vercel-Cache: STALE` 이 안 풀린다. 다섯 표본 전부 사본 생성 시각
#    `2026-09-09T21:59Z` 로 수렴 ⇒ 40시간 동안 **재생성 0회**(`revalidate = 60` 인데도).
#    그래서 방문자는 데모를 **켠 뒤에도** 「꺼져 있다」를 본다.
#
# -----------------------------------------------------------------------------
# 🔴🔴 모집단은 «선언» 이 아니라 **빌드 산출물의 프리렌더 목록**이다
# -----------------------------------------------------------------------------
# `export const revalidate` 를 grep 해서 모집단을 잡으면 안 된다. 654 가 실측으로 그것을
# 밟았다: 선언은 세 라우트에 있지만 `/products`·`/products/[id]` 는 **런타임에 동적**이라
# (`X-Nextjs-Prerender` 없음) 그 두 칸은 **영원히 안 무는 공허한 칸**이 된다.
#
# 🔴 그리고 반대쪽으로도 틀렸다. 654 는 살아 있는 URL **셋만** 재고 *"런타임 모집단은 1"*
#    이라고 적었는데, 빌드 산출물을 열어 보니 프리렌더되는 라우트는 **19개**이고 그중
#    레이아웃이 감싸는 것이 **15개**다(아래 bite 실측). 셋을 보고 모집단을 정한 것이
#    이 저장소가 이름 붙인 «전수조사는 어디를 봤나를 잰다» 그대로다.
#
# ⇒ 이 가드는 `.next/prerender-manifest.json` 의 `routes` 를 모집단으로 쓴다. 그것이
#   런타임 `X-Nextjs-Prerender: 1` 의 **빌드 시점 대응물**이고, 네트워크가 필요 없다.
#
# -----------------------------------------------------------------------------
# 🔴 주입 — 이 검사가 **공허해지는** 단 하나의 경로
# -----------------------------------------------------------------------------
# `DEMO_API_BASE` 가 없으면 판정은 `not-demo` 이고, **옛 결함 코드로 빌드해도 배너가 안
# 구워진다.** 그러면 이 가드는 「초록」인데 아무것도 증명하지 않는다 — 픽스처가 현실을
# 안 담은 초록이다.
# ⇒ 그래서 이 스크립트는 `DEMO_API_BASE` 가 **설정돼 있는지 먼저 단언하고**, 없으면
#   통과가 아니라 **RED** 로 죽는다. CI 의 빌드 스텝이 같은 값을 갖도록 `ci.yml` 의
#   `frontend-checks` 가 그 스텝에 env 를 건다(두 곳이 같은 값을 봐야 한다).
# 🔵 값은 **닿지 않는 주소**면 된다(`http://127.0.0.1:9`). 조회가 실패하면 판정이
#   `unavailable` 로 떨어지므로, 옛 코드라면 배너가 구워진다 — 네트워크 없이 결정적이다.
#
# -----------------------------------------------------------------------------
# 🔵 실측된 bite (2026-09-11, 이 티켓의 구현 중)
# -----------------------------------------------------------------------------
#   새 코드 (판정이 클라이언트)  →  19개 프리렌더 HTML 중 **0개**에 판정
#   옛 코드 (판정이 서버 껍데기)  →  18개 중 **15개**에 판정  ← 이 가드가 무는 자리
#
# -----------------------------------------------------------------------------
# 🔴 이 가드가 재지 **못하는** 것 (AC-3 의 「한계를 적어라」)
# -----------------------------------------------------------------------------
#  1. **캐시가 실제로 얼마나 낡는가** — 그것은 라이브 응답 헤더(`Age`)에만 있다.
#     이 가드는 «판정이 구워졌나» 만 잰다. 둘은 다른 축이고, 이 티켓의 진단(재생성이
#     착지하지 않는다)은 **여기서 안 나온다.**
#  2. **배너가 실제로 뜨는가** — 이 가드는 부재만 잰다. 「배너가 아예 사라졌다」는
#     여기서 초록이다. 그쪽은 `DemoBackendNotice.test.tsx` § B 가 문다.
#     🔴 두 검사는 **서로를 대신하지 못한다.**
#  3. **엣지/CDN 이 응답을 붙드는가** — 라우트 핸들러의 `no-store` 는
#     `demo-backend-state-route.test.ts` 가 단언한다. 여기서는 안 보인다.
# =============================================================================
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP="${ROOT}/projects/ecommerce-microservices-platform/apps/web-store"
NEXT_DIR="${APP}/.next"
MANIFEST="${NEXT_DIR}/prerender-manifest.json"
APP_HTML_DIR="${NEXT_DIR}/server/app"

# 판정 지문 — 배너의 testid 와 문구. 🔵 둘 다 보는 이유: testid 만 보면 문구를 그대로
# 둔 채 testid 를 지우는 판이 통과하고, 문구만 보면 문구를 바꾼 판이 통과한다.
VERDICT_RE='demo-backend-notice|데모 서버가 꺼져 있어'
# 레이아웃 생존 대조군 — 「배너가 없다」가 「페이지가 없다」로 성립하면 안 된다.
LAYOUT_RE='data-testid="theme-toggle"'

say()  { printf '%s\n' "$*"; }
die()  { printf '\n❌ check-prerendered-demo-verdict: %s\n' "$*" >&2; exit 1; }

# --- (1) 🔴 주입 단언 — 이것이 없으면 아래 전부가 공허하다 ---------------------
if [ -z "${DEMO_API_BASE:-}" ]; then
  die "\`DEMO_API_BASE\` 가 비어 있습니다.

이 값이 없으면 판정이 \`not-demo\` 라서 **옛 결함 코드로 빌드해도 배너가 안 구워집니다**
— 그러면 이 검사는 초록이지만 아무것도 증명하지 않습니다(공허한 통과).

  · CI:    ci.yml \`frontend-checks\` 의 «Build (ecommerce)» 스텝과 이 스텝에 **같은**
           env 를 걸어야 합니다. 한쪽만 걸면 빌드가 담은 것과 여기가 가정하는 것이 갈립니다.
  · 로컬:  DEMO_API_BASE=http://127.0.0.1:9 pnpm --filter web-store build
           DEMO_API_BASE=http://127.0.0.1:9 bash scripts/check-prerendered-demo-verdict.sh

🔵 닿지 않는 주소면 됩니다 — 조회가 실패하면 판정이 \`unavailable\` 로 떨어지므로
   네트워크 없이 결정적입니다."
fi

# --- (2) 실행 단언 — 빌드 산출물이 있는가 -------------------------------------
[ -f "$MANIFEST" ] || die "프리렌더 매니페스트가 없습니다: ${MANIFEST}
이 가드는 \`next build\` **뒤에** 돌아야 합니다(ci.yml 의 «Build (ecommerce)» 다음 스텝).
🔴 산출물이 없는 것은 «판정이 안 구워졌다» 가 아니라 **«아직 안 쟀다»** 입니다."
[ -d "$APP_HTML_DIR" ] || die "프리렌더된 HTML 디렉터리가 없습니다: ${APP_HTML_DIR}"

# --- (3) 모집단 — 매니페스트의 프리렌더 라우트 --------------------------------
n_routes="$(node -e 'const m=require(process.argv[1]);process.stdout.write(String(Object.keys(m.routes||{}).length))' "$MANIFEST" 2>/dev/null)" \
  || die "매니페스트를 못 읽었습니다: ${MANIFEST}"

mapfile -t html_files < <(find "$APP_HTML_DIR" -name '*.html' -type f 2>/dev/null | sort)
n_html="${#html_files[@]}"

# 🔴🔴 비공허성 — 모집단이 비면 아래 술어는 **언제나 참**이다. 그것은 통과가 아니다.
[ "${n_routes:-0}" -gt 0 ] || die "프리렌더된 라우트가 **0개**입니다.
그러면 아래 검사는 «아무것도 안 보고 통과» 입니다. 빌드가 실패했거나 앱이 전부 동적이
됐다는 뜻이고, 둘 다 이 가드가 조용히 지나갈 일이 아닙니다."
[ "$n_html" -gt 0 ] || die "프리렌더된 HTML 이 **0개**입니다(라우트는 ${n_routes}개).
매니페스트와 산출물이 어긋났습니다 — 이 상태의 통과는 의미가 없습니다."

# --- (4) 생존 대조군 — 「배너 없음」이 「페이지 없음」이 아님을 증명한다 --------
if ! grep -qlE "$LAYOUT_RE" "${html_files[@]}" 2>/dev/null; then
  die "프리렌더된 HTML 어디에도 스토어 레이아웃 지문(${LAYOUT_RE})이 없습니다.

🔴 그러면 «배너가 없다» 는 판정이 아닙니다 — 레이아웃 자체가 안 그려졌을 뿐일 수 있고,
   그 상태에서의 초록은 이 저장소가 이름 붙인 «머리만 렌더해도 감사는 초록» 입니다.
🔵 지문이 바뀐 것이라면 이 스크립트의 \`LAYOUT_RE\` 를 고치세요 — **검사를 지우지 말고.**"
fi

# --- (5) 술어 — 프리렌더된 출력에 판정이 있는가 -------------------------------
mapfile -t offenders < <(grep -rlE "$VERDICT_RE" "${html_files[@]}" 2>/dev/null | sort)
n_off="${#offenders[@]}"

if [ "$n_off" -gt 0 ]; then
  say ""
  say "❌ check-prerendered-demo-verdict: 프리렌더된 사본 ${n_off}개에 데모 백엔드 **판정이 구워져** 있습니다."
  say ""
  for f in "${offenders[@]}"; do say "  · ${f#"$APP_HTML_DIR"}"; done
  say ""
  say "🔴 이 판정은 빌드 시점의 사실이고, 이 배포에서 그 사본은 **재생성되지 않습니다**"
  say "   (실측: 40시간 동안 재생성 0회). ⇒ 방문자가 데모를 **켠 뒤에도** 「꺼져 있다」를 봅니다."
  say ""
  say "고치는 방향 — 캐시 수명을 줄이는 것이 **아닙니다**(재생성 자체가 안 착지합니다):"
  say "  판정을 서버 컴포넌트에서 빼고 **방문 시점에 브라우저가** 묻게 하세요."
  say "  기준 구현: src/widgets/demo-notice/DemoBackendNotice.tsx (껍데기는 무조건 렌더)"
  say "           + DemoBackendNoticeClient.tsx (탐침) + app/api/demo/backend-state/route.ts"
  exit 1
fi

say "check-prerendered-demo-verdict: OK — 프리렌더 라우트 ${n_routes}개 / HTML ${n_html}개, 구워진 판정 0건."
say "  (모집단 = 빌드 산출물의 프리렌더 목록. 선언 grep 이 아닙니다 — \`revalidate\` 선언은"
say "   런타임에 동적인 라우트에도 있어서 공허한 칸을 만듭니다.)"
say "  주입 확인: DEMO_API_BASE 설정됨 ⇒ 옛 코드였다면 배너가 구워졌을 조건입니다."
say "  🔴 이 검사가 재지 않는 것: 캐시가 얼마나 낡는가 · 배너가 실제로 뜨는가 · 엣지 캐시."
say "     각각 라이브 헤더 · DemoBackendNotice.test.tsx § B · demo-backend-state-route.test.ts 가 봅니다."
exit 0
